import { test, expect, openApp, reachCheckout, mockApi, realtimeStats, setScenario, authedApi } from '../helpers/app'

test.describe('Robustez do tempo real', () => {
  test('eventos duplicados e antigos não regridem o estado', async ({ page }) => {
    await openApp(page, '/nft/emerald-ape-042')
    await mockApi(page, 'POST', '/__mock/nft-update', { nftId: 'emerald-ape-042', editionId: 'emerald-ape-042-1of50', price: '1.50' })
    await expect(page.getByTestId('detail-price')).toContainText('1.50 ETH')
    const before = await realtimeStats(page)
    await mockApi(page, 'POST', '/__mock/socket/replay')
    await mockApi(page, 'POST', '/__mock/socket/stale', { nftId: 'emerald-ape-042', price: '0.01' })
    await expect.poll(async () => (await realtimeStats(page)).ignoredDuplicate).toBeGreaterThan(before.ignoredDuplicate)
    await expect.poll(async () => (await realtimeStats(page)).ignoredStale).toBeGreaterThan(before.ignoredStale)
    await expect(page.getByTestId('detail-price')).toContainText('1.50 ETH')
  })

  test('após desconexão, a reconexão reconcilia com a API REST', async ({ page }) => {
    await openApp(page, '/nft/emerald-ape-042')
    await setScenario(page, 'offline') // socket recusa reconexões
    await mockApi(page, 'POST', '/__mock/socket/disconnect')
    await expect(page.locator('html[data-realtime="connected"]')).toHaveCount(0)
    // Mudança acontece enquanto o cliente está desconectado (evento perdido)
    await mockApi(page, 'POST', '/__mock/nft-update', { nftId: 'emerald-ape-042', editionId: 'emerald-ape-042-1of50', price: '2.22' })
    await expect(page.getByTestId('detail-price')).toContainText('1.19 ETH')
    await setScenario(page, 'fast')
    await expect(page.locator('html[data-realtime="connected"]')).toHaveCount(1, { timeout: 15_000 })
    await expect(page.getByTestId('detail-price')).toContainText('2.22 ETH')
    await expect(page.getByText('Conexão em tempo real restabelecida')).toBeVisible()
  })

  test('queda durante pedido pendente e refresh recuperam o mesmo pedido', async ({ page }) => {
    test.setTimeout(60_000)
    await reachCheckout(page, { scenario: 'slow-payment' })
    await page.getByTestId('confirm-purchase').click()
    await page.getByRole('dialog').getByTestId('confirm-order').click()
    await expect(page.getByRole('heading', { name: 'Aguardando confirmação na rede' })).toBeVisible()
    const orderUrl = page.url()
    await mockApi(page, 'POST', '/__mock/socket/disconnect')
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Aguardando confirmação na rede' })).toBeVisible()
    expect(page.url()).toBe(orderUrl)
    await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible({ timeout: 20_000 })
    const orders = await authedApi<unknown[]>(page, 'GET', '/api/orders')
    expect(orders.body).toHaveLength(1)
    // Voltar ao checkout não recria o pedido (estado terminal)
    await page.goto('/cart')
    await expect(page.getByText('Seu carrinho está vazio')).toBeVisible()
  })

  test('eventos de pedido de outra sessão são ignorados', async ({ page }) => {
    await reachCheckout(page)
    await page.getByTestId('confirm-purchase').click()
    await page.getByRole('dialog').getByTestId('confirm-order').click()
    await expect(page.getByTestId('receipt-total')).toBeVisible({ timeout: 10_000 })
    // Logout + login de outro usuário: reenvio do order.updated (da Ana) não chega/é ignorado
    await page.goto('/profile')
    await page.getByRole('button', { name: 'Sair' }).click()
    await page.goto('/login')
    const d = page.getByRole('dialog')
    await d.getByPlaceholder('contato@email.com').fill('bruno@kurio.dev')
    await d.getByPlaceholder('Senha', { exact: true }).fill('Kurio@2026')
    await d.getByRole('button', { name: 'Entrar', exact: true }).click()
    await expect(page.locator('html[data-realtime="connected"]')).toHaveCount(1)
    const before = await realtimeStats(page)
    await mockApi(page, 'POST', '/__mock/socket/replay')
    await page.waitForTimeout(500)
    const after = await realtimeStats(page)
    expect(after.applied).toBe(before.applied)
  })
})
