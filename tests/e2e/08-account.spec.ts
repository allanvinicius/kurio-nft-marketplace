import { test, expect, openApp, login } from '../helpers/app'

// PNG 32x32 válido
const PNG = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAACAAAAAgCAIAAAD8GO2jAAAALUlEQVR4nGO81OXDQEvARFPTRy0YtWDUglELRi0YtWDUglELRi0YtWDUAioCAKORAehJ2bktAAAAAElFTkSuQmCC', 'base64')

test.describe('Perfil, avatar, senha e carteiras', () => {
  test('edição do perfil com validação, conflito e persistência @mobile', async ({ page }) => {
    await openApp(page, '/login?redirect=%2Fprofile')
    await login(page, 'ana')
    const name = page.getByLabel('Nome de exibição')
    await expect(name).toHaveValue('Ana Colecionadora')
    await name.fill('')
    await page.getByRole('button', { name: 'Salvar' }).click()
    await expect(name).toHaveAttribute('aria-invalid', 'true')
    await expect(page.locator('#pf-displayName-error')).toHaveText(/Informe o nome de exibição/)
    await expect(name).toBeFocused()

    await name.fill('Ana K.')
    await page.getByLabel('Nome de usuário').fill('bruno.nft')
    await page.getByRole('button', { name: 'Salvar' }).click()
    await expect(page.locator('#pf-username-error')).toHaveText(/já está em uso/)

    await page.getByLabel('Nome de usuário').fill('ana.k')
    await page.getByRole('button', { name: 'Salvar' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Perfil atualizado.' })).toBeVisible()
    await page.reload()
    await expect(page.getByLabel('Nome de exibição')).toHaveValue('Ana K.')
    await expect(page.getByLabel('Nome de usuário')).toHaveValue('ana.k')
  })

  test('avatar: envio, persistência e remoção; validação de formato', async ({ page }) => {
    await openApp(page, '/login?redirect=%2Fprofile')
    await login(page, 'ana')
    await page.getByTestId('avatar-input').setInputFiles({ name: 'doc.txt', mimeType: 'text/plain', buffer: Buffer.from('x') })
    await expect(page.locator('#pf-avatar-error')).toContainText('Formato não suportado')
    await page.getByTestId('avatar-input').setInputFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: PNG })
    await expect(page.getByTestId('avatar-preview').locator('img')).toBeVisible()
    await page.reload()
    await expect(page.getByTestId('avatar-preview').locator('img')).toBeVisible()
    await page.getByRole('button', { name: 'Remover', exact: true }).click()
    await expect(page.getByTestId('avatar-preview').locator('img')).toHaveCount(0)
  })

  test('alteração de senha: senha atual incorreta, sucesso e novo login', async ({ page }) => {
    await openApp(page, '/login?redirect=%2Fprofile')
    await login(page, 'ana')
    await page.getByLabel('Senha atual').fill('errada123')
    await page.getByLabel('Nova senha', { exact: true }).fill('NovaSenha1')
    await page.getByLabel('Confirmar nova senha').fill('NovaSenha1')
    await page.getByRole('button', { name: 'Salvar' }).click()
    await expect(page.locator('#pf-current-error')).toHaveText(/senha atual está incorreta/)
    await page.getByLabel('Senha atual').fill('Kurio@2026')
    await page.getByRole('button', { name: 'Salvar' }).click()
    await expect(page.getByRole('status').filter({ hasText: /senha alterada/i })).toBeVisible()
    // Sai e entra com a nova senha
    await page.getByRole('button', { name: 'Sair' }).click()
    await page.goto('/login')
    const d = page.getByRole('dialog')
    await d.getByPlaceholder('contato@email.com').fill('ana@kurio.dev')
    await d.getByPlaceholder('Senha', { exact: true }).fill('NovaSenha1')
    await d.getByRole('button', { name: 'Entrar', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
  })

  test('carteiras: cadastro com validação e carteira secundária', async ({ page }) => {
    await openApp(page, '/login?redirect=%2Fwallets')
    await login(page, 'bruno')
    const primary = page.getByRole('form', { name: 'Carteira principal' })
    await primary.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(primary.locator('#wp-address-error')).toBeVisible()
    await expect(primary.locator('#wp-network-error')).toHaveText(/Selecione uma rede/)

    await primary.getByLabel('Nome de exibição').fill('Bruno Nakamoto')
    await primary.getByLabel('Apelido da carteira').fill('Cofre')
    await primary.getByRole('combobox', { name: /Rede/ }).click()
    await page.getByRole('option', { name: 'Ethereum' }).click()
    await primary.getByLabel('Nome do perfil').fill('bruno.nft')
    await primary.getByLabel('Endereço da carteira').fill('0x123')
    await primary.getByRole('combobox', { name: /Tipo de carteira/ }).click()
    await page.getByRole('option', { name: 'MetaMask' }).click()
    await primary.getByLabel('Código de indicação').fill('KURIO-BRUNO')
    await primary.getByLabel('E-mail').fill('bruno@kurio.dev')
    await primary.getByRole('textbox', { name: /Nome ENS/ }).fill('bruno')
    await primary.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(primary.locator('#wp-address-error')).toContainText('Endereço inválido')
    await primary.getByLabel('Endereço da carteira').fill('0x5B2e8C1d4F7a9E3b6D0c2A8f1E5b7C9d3A6f41D7')
    await primary.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(primary.getByRole('status')).toContainText('Carteira principal salva')
    await page.reload()
    await expect(page.getByRole('form', { name: 'Carteira principal' }).getByLabel('Apelido da carteira')).toHaveValue('Cofre')

    // Secundária igual à principal (com novo endereço)
    await page.getByLabel('Igual à carteira principal').check()
    const secondary = page.getByRole('form', { name: 'Carteira secundária' })
    await secondary.getByLabel('Endereço da carteira').fill('0xA91F3c2b7D5e4F1a9B8c6D2e0F7a3B5c4D9E82C0')
    await secondary.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(page.getByText(/Carteira secundária salva/).first()).toBeVisible()
  })
})
